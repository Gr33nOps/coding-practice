MODEL SMALL
STACK 100H

DATA SEGMENT
    NUM1 DB 3
    NUM2 DB 5   
    LARGE DB ?
DATA ENDS

CODE SEGMENT
ASSUME CS:CODE, DS:DATA
START:
    MOV AX, DATA 
    MOV DS, AX 

    MOV AL, NUM1
    CMP AL, NUM2
    JAE IS_LARGE
    MOV AL, NUM2

IS_LARGE:
    MOV LARGE, AL
    MOV AH,4CH
    INT 21H
CODE ENDS
END START